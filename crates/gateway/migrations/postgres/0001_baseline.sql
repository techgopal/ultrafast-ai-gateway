-- Rate limits of the gateway, a team, a user or a key. Each limit is
-- optional: NULL is no limit of that kind.
CREATE TABLE rate_limits (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id              BIGINT NOT NULL DEFAULT 1,
    scope               TEXT   COLLATE "C" NOT NULL CHECK (scope IN ('gateway', 'team', 'user', 'key')),
    -- NULL for the gateway, the id of the team, user or key otherwise.
    scope_id            BIGINT,
    requests_per_minute BIGINT CHECK (requests_per_minute IS NULL OR requests_per_minute > 0),
    tokens_per_minute   BIGINT CHECK (tokens_per_minute IS NULL OR tokens_per_minute > 0),
    concurrent          BIGINT CHECK (concurrent IS NULL OR concurrent > 0),
    created_at          TEXT   COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    UNIQUE (org_id, scope, scope_id),
    CHECK ((scope = 'gateway') = (scope_id IS NULL))
);

-- NULLs are distinct in a UNIQUE constraint, so the gateway's single
-- limit needs this index to stay single.
CREATE UNIQUE INDEX idx_rate_limits_subject ON rate_limits (org_id, scope, COALESCE(scope_id, 0));

-- Spending budgets of the gateway, a team, a user or a key, per UTC
-- calendar period.
CREATE TABLE budgets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id        BIGINT NOT NULL DEFAULT 1,
    scope         TEXT   COLLATE "C" NOT NULL CHECK (scope IN ('gateway', 'team', 'user', 'key')),
    -- NULL for the gateway, the id of the team, user or key otherwise.
    scope_id      BIGINT,
    amount_micros BIGINT NOT NULL CHECK (amount_micros > 0),
    period        TEXT   COLLATE "C" NOT NULL CHECK (period IN ('daily', 'weekly', 'monthly')),
    action        TEXT   COLLATE "C" NOT NULL CHECK (action IN ('block', 'alert')),
    created_at    TEXT   COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    UNIQUE (org_id, scope, scope_id, period),
    CHECK ((scope = 'gateway') = (scope_id IS NULL))
);

CREATE UNIQUE INDEX idx_budgets_subject ON budgets (org_id, scope, COALESCE(scope_id, 0), period);

-- What a budget has spent in one period; `period_start` is the UTC date the
-- period began on, as YYYY-MM-DD.
CREATE TABLE budget_usage (
    budget_id    BIGINT NOT NULL REFERENCES budgets (id) ON DELETE CASCADE,
    period_start TEXT   COLLATE "C" NOT NULL,
    spent_micros BIGINT NOT NULL DEFAULT 0,
    -- 1 once the alert of this period was written.
    alerted      BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (budget_id, period_start)
);

-- Alerts: where notifications go (channels), when they are made (rules),
-- what a rule has seen (state) and what was sent (events).
CREATE TABLE alert_channels (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     BIGINT NOT NULL DEFAULT 1,
    name       TEXT   COLLATE "C" NOT NULL,
    kind       TEXT   COLLATE "C" NOT NULL CHECK (kind IN ('webhook','slack')),
    url_enc    BYTEA  NOT NULL,
    url_host   TEXT   COLLATE "C" NOT NULL,
    secret_enc BYTEA  NOT NULL,
    enabled    BIGINT NOT NULL DEFAULT 1,
    created_at TEXT   COLLATE "C" NOT NULL,
    UNIQUE (org_id, name)
);
CREATE TABLE alert_rules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     BIGINT NOT NULL DEFAULT 1,
    name       TEXT   COLLATE "C" NOT NULL,
    kind       TEXT   COLLATE "C" NOT NULL CHECK (kind IN ('budget','error_rate','circuit_open')),
    params     TEXT   COLLATE "C" NOT NULL,   -- JSON, validated per kind
    enabled    BIGINT NOT NULL DEFAULT 1,
    created_at TEXT   COLLATE "C" NOT NULL,
    UNIQUE (org_id, name)
);
CREATE TABLE alert_rule_channels (
    rule_id    BIGINT NOT NULL REFERENCES alert_rules(id) ON DELETE CASCADE,
    channel_id BIGINT NOT NULL REFERENCES alert_channels(id) ON DELETE CASCADE,
    PRIMARY KEY (rule_id, channel_id)
);
CREATE TABLE alert_state (       -- one row per rule and subject while known
    rule_id BIGINT NOT NULL REFERENCES alert_rules(id) ON DELETE CASCADE,
    subject TEXT   COLLATE "C" NOT NULL,   -- e.g. 'budget:12:2026-10-05', 'route:chat'
    firing  BIGINT NOT NULL,
    since   TEXT   COLLATE "C" NOT NULL,
    PRIMARY KEY (rule_id, subject)
);
CREATE TABLE alert_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     BIGINT NOT NULL DEFAULT 1,
    rule_id    BIGINT REFERENCES alert_rules(id) ON DELETE SET NULL,
    rule_name  TEXT   COLLATE "C" NOT NULL,
    kind       TEXT   COLLATE "C" NOT NULL,
    subject    TEXT   COLLATE "C" NOT NULL,
    state      TEXT   COLLATE "C" NOT NULL CHECK (state IN ('firing','resolved','test')),
    summary    TEXT   COLLATE "C" NOT NULL,
    details    TEXT   COLLATE "C" NOT NULL,   -- JSON, metadata only
    at         TEXT   COLLATE "C" NOT NULL,
    deliveries TEXT   COLLATE "C" NOT NULL DEFAULT '[]'
);
CREATE INDEX alert_events_at ON alert_events (org_id, at);

-- The scope of a limit or a budget is not a foreign key (it points at one of
-- three tables), so what a deleted team or user leaves behind is removed
-- here. A deleted user or team also leaves the request logs' owner column
-- empty. These are the equivalents of SQLite's triggers 0007, 0008 and 0010.
CREATE FUNCTION uf_team_deleted() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM rate_limits WHERE scope = 'team' AND scope_id = OLD.id;
    DELETE FROM budgets WHERE scope = 'team' AND scope_id = OLD.id;
    UPDATE request_logs SET team_id = NULL WHERE team_id = OLD.id;
    RETURN NULL;
END;
$$;

CREATE FUNCTION uf_user_deleted() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM rate_limits WHERE scope = 'user' AND scope_id = OLD.id;
    DELETE FROM budgets WHERE scope = 'user' AND scope_id = OLD.id;
    UPDATE request_logs SET user_id = NULL WHERE user_id = OLD.id;
    RETURN NULL;
END;
$$;

CREATE TRIGGER team_deleted AFTER DELETE ON teams
    FOR EACH ROW EXECUTE FUNCTION uf_team_deleted();
CREATE TRIGGER user_deleted AFTER DELETE ON users
    FOR EACH ROW EXECUTE FUNCTION uf_user_deleted();
