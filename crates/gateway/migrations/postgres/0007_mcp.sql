-- MCP servers the gateway proxies, the tools they offer and who may call
-- each tool. A sync that no longer sees a tool marks it removed instead of
-- deleting it, so its grants survive the tool coming back. This is SQLite
-- migration 0021.
CREATE TABLE mcp_servers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id BIGINT NOT NULL DEFAULT 1,
  name TEXT COLLATE "C" NOT NULL, url TEXT COLLATE "C" NOT NULL,
  auth_kind TEXT COLLATE "C" NOT NULL DEFAULT 'none' CHECK (auth_kind IN ('none','bearer','header')),
  auth_header TEXT COLLATE "C",
  auth_secret_enc TEXT COLLATE "C",
  enabled BIGINT NOT NULL DEFAULT 1,
  description TEXT COLLATE "C" NOT NULL DEFAULT '',
  created_at TEXT COLLATE "C" NOT NULL, updated_at TEXT COLLATE "C" NOT NULL,
  last_sync_at TEXT COLLATE "C",
  last_sync_error TEXT COLLATE "C",
  UNIQUE (org_id, name));
CREATE TABLE mcp_tools (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id BIGINT NOT NULL REFERENCES mcp_servers(id) ON DELETE CASCADE,
  name TEXT COLLATE "C" NOT NULL, title TEXT COLLATE "C",
  description TEXT COLLATE "C" NOT NULL DEFAULT '',
  input_schema TEXT COLLATE "C" NOT NULL,
  output_schema TEXT COLLATE "C", annotations TEXT COLLATE "C",
  enabled BIGINT NOT NULL DEFAULT 0,
  removed_at TEXT COLLATE "C",
  UNIQUE (server_id, name));
CREATE TABLE mcp_tool_grants (
  tool_id BIGINT NOT NULL REFERENCES mcp_tools(id) ON DELETE CASCADE,
  team_id BIGINT REFERENCES teams(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  CHECK (team_id IS NULL OR user_id IS NULL));
CREATE UNIQUE INDEX mcp_tool_grants_unique
  ON mcp_tool_grants (tool_id, COALESCE(team_id, 0), COALESCE(user_id, 0));
CREATE INDEX mcp_tool_grants_team ON mcp_tool_grants (team_id);
CREATE INDEX mcp_tool_grants_user ON mcp_tool_grants (user_id);
